"""
Record the outputs shown by the ▶ buttons when the slides are opened WITHOUT serve.py
=====================================================================================
Runs every steps/*/demo.py (and solution.py, when present) and the Icaros demos
(demos/*/*.mas2i, only if Icaros is installed -- see slides/serve.py), and writes slides/recordings.js.

    uv run scripts/record_outputs.py
    uv run scripts/record_outputs.py steps/02-tools/demo.py   # re-record only some scripts

The mock API is started automatically if needed.
"""

import datetime
import json
import signal
import subprocess
import sys
import time
from pathlib import Path

from lab.config import MODEL

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "slides" / "recordings.js"

sys.path.insert(0, str(REPO_ROOT / "slides"))
from serve import Unavailable, command_for, ensure_mock_api  # noqa: E402


def load_existing() -> dict:
    """Reads the current recordings, so that a partial re-recording keeps the others."""
    if not OUTPUT.exists():
        return {}
    text = OUTPUT.read_text()
    return json.loads(text[text.index("{"):text.rindex("}") + 1])


def main() -> None:
    scripts = sys.argv[1:] or sorted(
        str(p.relative_to(REPO_ROOT)) for p in REPO_ROOT.glob("steps/*/*.py") if p.name in ("demo.py", "solution.py")
    ) + sorted(str(p.relative_to(REPO_ROOT)) for p in REPO_ROOT.glob("demos/*/*.mas2i"))
    recordings = load_existing()
    signal.signal(signal.SIGTERM, signal.default_int_handler)
    mock = ensure_mock_api()
    time.sleep(0.5)
    try:
        for script in scripts:
            print(f"▶ {script} ...", end=" ", flush=True)
            try:
                cmd, env = command_for(REPO_ROOT / script)
            except Unavailable as e:
                print(f"skipped: {e}" + (" (keeping the old recording)" if script in recordings else ""))
                continue
            start = time.time()
            result = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True, env=env)
            seconds = round(time.time() - start, 1)
            output = result.stdout + result.stderr
            if result.returncode != 0:
                output += f"\n[exit code {result.returncode}]\n"
            recordings[script] = {
                "output": output,
                "seconds": seconds,
                "model": MODEL,
                "date": datetime.date.today().isoformat(),
            }
            print(f"{seconds}s" + ("" if result.returncode == 0 else f"  (exit code {result.returncode})"))
    finally:
        if mock:
            mock.terminate()

    OUTPUT.write_text(
        "// Generated by scripts/record_outputs.py — recorded outputs replayed by the ▶ buttons\n"
        "// when the slides are opened without `uv run slides/serve.py`.\n"
        f"window.RECORDINGS = {json.dumps(dict(sorted(recordings.items())), indent=1, ensure_ascii=False)};\n"
    )
    print(f"Saved {len(recordings)} recordings to {OUTPUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
